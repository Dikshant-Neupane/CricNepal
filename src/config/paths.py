"""
Central path configuration for CricNepal project.

All data paths are resolved from environment variables with sensible defaults.
This ensures the project runs on any machine without hardcoded paths.

Environment Variables:
    CRIC_DATA_DIR   — Root of external cricket data (parquet files, rosters)
                      Default: <repo-parent>/Cric_Data/data (env CRIC_DATA_DIR
                      overrides; falls back to the bundled data/ dir when the
                      external directory is absent)
    CRICNEPAL_ROOT  — Project root (auto-detected if unset)
"""

import os
from pathlib import Path


def _project_root() -> Path:
    """Detect project root (3 levels up from this file: src/config/paths.py)."""
    return Path(__file__).resolve().parent.parent.parent


# ── Project paths ────────────────────────────────────────────
PROJECT_ROOT = Path(os.environ.get("CRICNEPAL_ROOT", str(_project_root())))
DATA_DIR = PROJECT_ROOT / "data"
NORMALIZED_DIR = DATA_DIR / "normalized"
EXPORT_DIR = DATA_DIR / "exports"
RAW_DIR = DATA_DIR / "raw"
DELIVERABLES_DIR = PROJECT_ROOT / "deliverables"

# ── External data paths ─────────────────────────────────────
_cric_data_default = str(PROJECT_ROOT.parent / "Cric_Data" / "data")
CRIC_DATA_DIR = Path(os.environ.get("CRIC_DATA_DIR", _cric_data_default))

if not CRIC_DATA_DIR.exists():
    # If external Cric_Data is missing (e.g. in Streamlit Cloud),
    # fall back to the bundled production_assets directory first.
    _production_assets = DATA_DIR / "production_assets"
    if _production_assets.exists():
        CRIC_DATA_DIR = _production_assets
    else:
        CRIC_DATA_DIR = DATA_DIR
    
# CANONICAL DATA LAYER (plan 1.2, 2026-10-29): data/normalized is the
# canonical layer (NORMALIZED_DIR). The final/parquet copies below are
# a SERVED PROJECTION of it, regenerated by
# scripts/sync_final_from_normalized.py — never edit them by hand and
# never treat them as a second source of truth.
PARQUET_DIR = CRIC_DATA_DIR / "final" / "parquet"
ROSTER_DIR = CRIC_DATA_DIR / "player_rosters"
PROFILES_DIR = CRIC_DATA_DIR / "player_profiles"


def resolve_ball_by_ball_parquet() -> Path:
    """Ball-by-ball parquet: the canonical normalized file if present,
    else the served final/parquet projection.

    data/normalized/ball_by_ball_normalized.parquet is not in the repo
    (untracked; *.parquet is gitignored), so a fresh clone has only
    data/final/parquet/ball_by_ball.parquet — a projection of the same
    data, regenerated by scripts/sync_final_from_normalized.py. The
    dashboard loaders and scripts/prepare_season_features.py already
    fall back this way (audit A7); the analytics modules now share
    this resolver instead of crashing with FileNotFoundError.
    Raises FileNotFoundError naming both candidates if neither exists.
    """
    canonical = NORMALIZED_DIR / "ball_by_ball_normalized.parquet"
    if canonical.exists():
        return canonical
    fallback = PARQUET_DIR / "ball_by_ball.parquet"
    if fallback.exists():
        return fallback
    raise FileNotFoundError(
        f"ball-by-ball parquet not found: checked {canonical} and {fallback}"
    )


def ensure_dirs() -> None:
    """Create output directories if they don't exist."""
    for d in [DATA_DIR, NORMALIZED_DIR, EXPORT_DIR, DELIVERABLES_DIR]:
        d.mkdir(parents=True, exist_ok=True)
